package controller

import (
	"bytes"
	"context"
	"fmt"
	"sort"

	corev1 "k8s.io/api/core/v1"
	"k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/controller/controllerutil"

	matrixdbv1alpha1 "github.com/matrixdb-io/matrixdb-operator/api/v1alpha1"
	"github.com/matrixdb-io/matrixdb-operator/pkg/constants"
)

func (r *MatrixDBClusterReconciler) reconcileConfigMap(ctx context.Context, cluster *matrixdbv1alpha1.MatrixDBCluster) (string, error) {
	cmName := fmt.Sprintf("%s-config", cluster.Name)

	configContent := r.renderMyCnf(cluster)

	cm := &corev1.ConfigMap{}
	err := r.Get(ctx, types.NamespacedName{Namespace: cluster.Namespace, Name: cmName}, cm)
	if err != nil {
		if errors.IsNotFound(err) {
			newCM := &corev1.ConfigMap{
				ObjectMeta: metav1.ObjectMeta{
					Name:      cmName,
					Namespace: cluster.Namespace,
					Labels: map[string]string{
						constants.LabelAppName:      "matrixdb",
						constants.LabelAppInstance: cluster.Name,
						constants.LabelClusterName:  cluster.Name,
						constants.LabelAppManagedBy: "matrixdb-operator",
					},
				},
				Data: map[string]string{
					"matrixdb.cnf": configContent,
				},
			}
			if err := controllerutil.SetControllerReference(cluster, newCM, r.Scheme); err != nil {
				return "", fmt.Errorf("failed setting controller reference on configmap: %w", err)
			}
			if err := r.Create(ctx, newCM); err != nil {
				return "", fmt.Errorf("failed to create configmap %s: %w", cmName, err)
			}
			r.Log.Info("Created MySQL configuration ConfigMap", "configMap", cmName)
			return cmName, nil
		}
		return "", fmt.Errorf("failed to get configmap %s: %w", cmName, err)
	}

	// Update if configuration changed
	if cm.Data["matrixdb.cnf"] != configContent {
		cm.Data["matrixdb.cnf"] = configContent
		if err := r.Update(ctx, cm); err != nil {
			return "", fmt.Errorf("failed to update configmap %s: %w", cmName, err)
		}
		r.Log.Info("Updated MySQL configuration ConfigMap", "configMap", cmName)
	}

	return cmName, nil
}

func (r *MatrixDBClusterReconciler) renderMyCnf(cluster *matrixdbv1alpha1.MatrixDBCluster) string {
	timeout := cluster.Spec.SemiSyncTimeoutMS
	if timeout <= 0 {
		timeout = constants.DefaultSemiSyncTimeoutMS
	}

	// Calculate wait_for_slave_count as (replicas - 1) / 2 or at least 1
	waitSlaveCount := int((cluster.Spec.Replicas - 1) / 2)
	if waitSlaveCount < 1 && cluster.Spec.Replicas > 1 {
		waitSlaveCount = 1
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by MatrixDB-Operator - Production Configuration\n")
	buf.WriteString("[mysqld]\n")
	buf.WriteString("binlog_format = ROW\n")
	buf.WriteString("gtid_mode = ON\n")
	buf.WriteString("enforce_gtid_consistency = ON\n")
	buf.WriteString("log_replica_updates = ON\n")
	buf.WriteString("binlog_expire_logs_seconds = 604800\n")
	buf.WriteString("max_connections = 1000\n")
	buf.WriteString("character_set_server = utf8mb4\n")
	buf.WriteString("collation_server = utf8mb4_unicode_ci\n")
	buf.WriteString("skip_name_resolve = 1\n")
	buf.WriteString("innodb_file_per_table = 1\n")
	buf.WriteString("relay_log_recovery = OFF\n")
	buf.WriteString("replica_parallel_type = LOGICAL_CLOCK\n")
	buf.WriteString("replica_preserve_commit_order = ON\n")

	// Auto-tuned innodb_buffer_pool_size if not explicitly overridden
	autoTuned := r.getAutoTunedBufferPoolSize(cluster)
	if autoTuned != "" {
		if cluster.Spec.MysqlConfig == nil || cluster.Spec.MysqlConfig["innodb_buffer_pool_size"] == "" {
			buf.WriteString(fmt.Sprintf("innodb_buffer_pool_size = %s\n", autoTuned))
		}
	}

	// Append custom configurations if present
	if len(cluster.Spec.MysqlConfig) > 0 {
		buf.WriteString("\n# Custom User Configurations\n")
		var keys []string
		for k := range cluster.Spec.MysqlConfig {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			buf.WriteString(fmt.Sprintf("%s = %s\n", k, cluster.Spec.MysqlConfig[k]))
		}
	}

	return buf.String()
}
